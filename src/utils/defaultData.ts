export const STORAGE_KEY_ALBUMS = "shotpik_studio_albums_v5";

export function loadStoredAlbums(): Album[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEY_ALBUMS);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        // Đảm bảo album Hương có đủ 100 ảnh nếu bản cũ trong máy chỉ có 50 ảnh
        return parsed.map((alb: Album) => {
          if (alb.id === 'album-huong-drive' && alb.photos.length < 100) {
            const initialHuong = INITIAL_ALBUMS.find(a => a.id === 'album-huong-drive');
            if (initialHuong) {
              return initialHuong;
            }
          }
          return alb;
        });
      }
    }
  } catch (e) {
    console.error("Lỗi khi đọc album từ localStorage:", e);
  }
  return INITIAL_ALBUMS;
}

export function saveStoredAlbums(albums: Album[]) {
  try {
    localStorage.setItem(STORAGE_KEY_ALBUMS, JSON.stringify(albums));
  } catch (e) {
    console.error("Lỗi khi lưu album vào localStorage:", e);
  }
}
